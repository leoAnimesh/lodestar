import AppKit
import LodestarCore

/// Records text copied to the general pasteboard by polling `changeCount`
/// (macOS has no pasteboard change notification). Entries marked concealed
/// or transient by password managers (nspasteboard.org convention) are skipped.
final class ClipboardHistory {
    struct Entry: Codable, Equatable {
        let text: String
        let date: Date
        let sourceApp: String?
    }

    private(set) var entries: [Entry] = []
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    var limit: Int {
        didSet { if entries.count > limit { entries.removeLast(entries.count - limit); save() } }
    }
    private let storeURL: URL

    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
    ]

    init(limit: Int, storeURL: URL) {
        self.limit = limit
        self.storeURL = storeURL
        if let data = try? Data(contentsOf: storeURL),
           let decoded = try? JSONDecoder().decode([Entry].self, from: data) {
            entries = decoded
        }
    }

    func start() {
        timer?.invalidate()
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.2
    }

    func stop() { timer?.invalidate(); timer = nil }

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        let types = Set((pb.types ?? []).map(\.rawValue))
        guard types.isDisjoint(with: ClipboardHistory.ignoredTypes) else { return }
        guard let text = pb.string(forType: .string),
              !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty else { return }
        entries.removeAll { $0.text == text }
        entries.insert(Entry(text: text, date: Date(), sourceApp: NSWorkspace.shared.frontmostApplication?.localizedName), at: 0)
        if entries.count > limit { entries.removeLast(entries.count - limit) }
        save()
    }

    func remove(_ entry: Entry) { entries.removeAll { $0 == entry }; save() }
    func clear() { entries.removeAll(); save() }

    private func save() {
        do {
            try FileManager.default.createDirectory(at: storeURL.deletingLastPathComponent(), withIntermediateDirectories: true)
            try JSONEncoder().encode(entries).write(to: storeURL, options: .atomic)
            // Clipboard contents can be sensitive: keep the file owner-only.
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storeURL.path)
        } catch {
            NSLog("Lodestar: failed to save clipboard history: \(error)")
        }
    }
}

final class ClipboardHistoryScreen: ListScreen {
    let title = "Clipboard History"
    let placeholder = "Search clipboard history…"
    weak var host: ScreenHost?
    private let history: ClipboardHistory

    init(history: ClipboardHistory) { self.history = history }

    func search(_ query: String) -> [LauncherItem] {
        let formatter = RelativeDateTimeFormatter()
        formatter.unitsStyle = .abbreviated
        var rows: [LauncherItem] = []
        for (i, entry) in history.entries.enumerated() {
            let single = entry.text.replacingOccurrences(of: "\n", with: " ⏎ ")
            var match: FuzzyMatch?
            if !query.isEmpty {
                // Long entries: plain substring search is more useful than fuzzy.
                if entry.text.count > 120 || query.count > 30 {
                    guard entry.text.localizedCaseInsensitiveContains(query) else { continue }
                } else {
                    match = FuzzyMatcher.match(query, in: single)
                    guard match != nil else { continue }
                }
            }
            let text = entry.text
            rows.append(LauncherItem(
                id: "clip:\(i):\(text.hashValue)",
                title: String(single.prefix(140)),
                subtitle: nil,
                icon: .symbol("doc.on.clipboard"),
                accessory: [entry.sourceApp, formatter.localizedString(for: entry.date, relativeTo: Date())]
                    .compactMap { $0 }.joined(separator: " · "),
                actions: [
                    LauncherAction("Paste", symbol: "doc.on.clipboard") { .closeThen { SystemActions.paste(text) } },
                    LauncherAction("Copy", symbol: "doc.on.doc") { SystemActions.copy(text); return .close },
                    LauncherAction("Show Full Text", symbol: "text.alignleft") { .detail(title: "Clipboard Entry", text: text) },
                    LauncherAction("Delete Entry", symbol: "trash") { [weak self] in
                        self?.history.remove(entry)
                        if let self { self.host?.setItems(self.search(query), for: self) }
                        return .toast("Deleted")
                    },
                    LauncherAction("Clear All History", symbol: "trash.slash") { [weak self] in
                        guard SystemActions.confirm("Clear clipboard history?", button: "Clear") else { return .stay }
                        self?.history.clear()
                        if let self { self.host?.setItems([], for: self) }
                        return .toast("History cleared")
                    },
                ],
                matchedIndices: match?.matchedIndices.filter { $0 < 140 } ?? [],
                tracksUsage: false
            ))
            if rows.count >= 200 { break }
        }
        return rows
    }
}
