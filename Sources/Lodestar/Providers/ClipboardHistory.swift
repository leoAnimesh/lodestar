/// Records what's copied to the general pasteboard by polling `changeCount`
/// (macOS has no pasteboard change notification): text (with its RTF/HTML
/// formatting, if any), links, colors, images and file references, plus the
/// app that was frontmost and the time.
///
/// Entries marked concealed or transient by password managers
/// (nspasteboard.org convention) are skipped. The list is saved owner-only
/// (0600) to clipboard.json; images and formatting are side files in an
/// owner-only (0700) `clipboard/` folder next to it, deleted with their entry.
/// The pure parts (model, detection, pruning, migration) are in
/// LodestarCore/ClipboardModel.swift.
final class ClipboardHistory {
    private(set) var entries: [ClipboardEntry] = []
    /// nil keeps everything in memory (the snapshot tour).
    private let storeURL: URL?
    let filesDirectory: URL
    private var lastChangeCount = NSPasteboard.general.changeCount
    private var timer: Timer?
    let workQueue = DispatchQueue(label: "lodestar.clipboard.images", qos: .utility)
    /// Called on the main thread after any change (new copy, delete, pin...).
    var onChange: (() -> Void)?

    var limit: Int {
        didSet { apply(ClipboardHistoryLogic.prune(entries, limit: limit)) }
    }

    /// Images bigger than this (encoded) aren't recorded.
    static let maxImageBytes = 30 * 1024 * 1024
    /// RTF/HTML bigger than this is dropped; the plain text is still kept.
    static let maxRichTextBytes = 2 * 1024 * 1024
    static let thumbnailPixels = 128

    static let ignoredTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.typeit4me.clipping",
        "de.petermaurer.TransientPasteboardType",
        "Pasteboard generator type",
        "net.antelle.keeweb",
    ]

    init(limit: Int, storeURL: URL?, filesDirectory: URL) {
        self.limit = limit
        self.storeURL = storeURL
        self.filesDirectory = filesDirectory
        load()
    }

    /// The real history in ~/Library/Application Support/Lodestar.
    static func standard(limit: Int) -> ClipboardHistory {
        ClipboardHistory(limit: limit,
                         storeURL: LodestarPaths.supportDirectory.appendingPathComponent("clipboard.json"),
                         filesDirectory: LodestarPaths.supportDirectory.appendingPathComponent("clipboard", isDirectory: true))
    }

    func start() {
        timer?.invalidate()
        lastChangeCount = NSPasteboard.general.changeCount
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in self?.poll() }
        timer?.tolerance = 0.2
    }

    func stop() { timer?.invalidate(); timer = nil }

    func fileURL(_ name: String) -> URL { filesDirectory.appendingPathComponent(name) }

    // MARK: Capture

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChangeCount else { return }
        lastChangeCount = pb.changeCount
        capture(from: pb)
    }

    /// Records whatever `pb` holds (the general pasteboard, or a private one in the self-test).
    func capture(from pb: NSPasteboard) {
        let types = pb.types ?? []
        guard Set(types.map(\.rawValue)).isDisjoint(with: ClipboardHistory.ignoredTypes) else { return }
        let front = NSWorkspace.shared.frontmostApplication
        let source = (name: front?.localizedName, bundleID: front?.bundleIdentifier)
        let now = Date()

        // Files first: Finder also puts the file names on the pasteboard as text.
        if let urls = pb.readObjects(forClasses: [NSURL.self], options: [.urlReadingFileURLsOnly: true]) as? [URL], !urls.isEmpty {
            let paths = urls.map(\.path)
            insert(ClipboardEntry(kind: .file, text: paths.joined(separator: "\n"), date: now,
                                  sourceApp: source.name, sourceBundleID: source.bundleID))
            return
        }
        if let text = pb.string(forType: .string), !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            var entry = ClipboardEntry.text(text, date: now, sourceApp: source.name, sourceBundleID: source.bundleID)
            if entry.kind == .text { entry.richText = saveRichText(from: pb, types: types) }
            insert(entry)
            return
        }
        let imageData = types.contains(.png) ? pb.data(forType: .png) : types.contains(.tiff) ? pb.data(forType: .tiff) : nil
        if let imageData {
            let isPNG = types.contains(.png)
            workQueue.async { [weak self] in
                guard let self, let processed = ClipboardImageProcessor.process(imageData, isPNG: isPNG) else { return }
                DispatchQueue.main.async {
                    self.insertImage(processed, date: now, sourceApp: source.name, sourceBundleID: source.bundleID)
                }
            }
        }
    }

    private func saveRichText(from pb: NSPasteboard, types: [NSPasteboard.PasteboardType]) -> ClipboardRichText? {
        let candidates: [(NSPasteboard.PasteboardType, ClipboardRichText.Format)] = [(.rtf, .rtf), (.html, .html)]
        for (type, format) in candidates where types.contains(type) {
            guard let data = pb.data(forType: type), !data.isEmpty, data.count <= ClipboardHistory.maxRichTextBytes else { continue }
            let name = "\(UUID().uuidString).\(format.rawValue)"
            guard writeFile(name, data) else { return nil }
            return ClipboardRichText(format: format, fileName: name)
        }
        return nil
    }

    private func insertImage(_ image: ClipboardImageProcessor.Result, date: Date, sourceApp: String?, sourceBundleID: String?) {
        // The same image again: move it up instead of writing new files.
        if let existing = entries.first(where: { $0.image?.digest == image.digest }) {
            var entries = ClipboardHistoryLogic.promote(existing.id, in: self.entries, date: date)
            entries[0].sourceApp = sourceApp
            entries[0].sourceBundleID = sourceBundleID
            self.entries = entries
            save()
            onChange?()
            return
        }
        let base = UUID().uuidString
        let fileName = "\(base).png"
        guard writeFile(fileName, image.png) else { return }
        var thumbName: String? = "\(base)-thumb.png"
        if let thumb = image.thumbnail, let name = thumbName, writeFile(name, thumb) {} else { thumbName = nil }
        let info = ClipboardImageInfo(fileName: fileName, thumbnailFileName: thumbName, width: image.width, height: image.height,
                                      byteSize: image.png.count, digest: image.digest)
        insert(ClipboardEntry(kind: .image, text: nil, date: date, sourceApp: sourceApp, sourceBundleID: sourceBundleID, image: info))
    }

    /// Adds an entry (used by capture and by the snapshot tour's samples).
    func insert(_ entry: ClipboardEntry) {
        apply(ClipboardHistoryLogic.insert(entry, into: entries, limit: limit))
    }

    /// Stores an image the way a copied one would be (snapshot tour samples).
    func insertImage(data: Data, date: Date, sourceApp: String?, sourceBundleID: String?) {
        guard let processed = ClipboardImageProcessor.process(data, isPNG: true) else { return }
        insertImage(processed, date: date, sourceApp: sourceApp, sourceBundleID: sourceBundleID)
    }

    // MARK: Editing

    func remove(_ id: UUID) { apply(ClipboardHistoryLogic.remove(id, from: entries)) }
    func clear() { apply(ClipboardHistoryLogic.clear(entries)) }

    func setPinned(_ pinned: Bool, id: UUID) {
        entries = ClipboardHistoryLogic.setPinned(pinned, id: id, in: entries)
        save()
        onChange?()
    }

    private func apply(_ change: ClipboardHistoryLogic.Change) {
        let changed = change.entries != entries || !change.removedFiles.isEmpty
        entries = change.entries
        for name in change.removedFiles { try? FileManager.default.removeItem(at: fileURL(name)) }
        guard changed else { return }
        save()
        onChange?()
    }

    // MARK: Writing back to the pasteboard

    /// Puts an entry back on the pasteboard. `plainText` writes only its text
    /// form (no formatting; a file's path, not the file). The entry moves to
    /// the top; the write itself isn't recorded as a new copy.
    func write(_ entry: ClipboardEntry, plainText: Bool = false) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch entry.kind {
        case .image:
            if let image = entry.image, let data = try? Data(contentsOf: fileURL(image.fileName)) {
                pb.setData(data, forType: .png)
                if !plainText, let tiff = NSImage(data: data)?.tiffRepresentation { pb.setData(tiff, forType: .tiff) }
            }
        case .file:
            if plainText {
                pb.setString(entry.filePaths.joined(separator: "\n"), forType: .string)
            } else {
                pb.writeObjects(entry.filePaths.map { URL(fileURLWithPath: $0) as NSURL })
            }
        case .link:
            let text = entry.text ?? ""
            if !plainText, let url = ClipboardClassifier.link(in: text) { pb.writeObjects([url as NSURL]) }
            pb.setString(text, forType: .string)
        case .text, .color:
            pb.setString(entry.text ?? "", forType: .string)
            if !plainText, let rich = entry.richText, let data = try? Data(contentsOf: fileURL(rich.fileName)) {
                pb.setData(data, forType: rich.format == .rtf ? .rtf : .html)
            }
        }
        lastChangeCount = pb.changeCount
        entries = ClipboardHistoryLogic.promote(entry.id, in: entries, date: Date())
        save()
        onChange?()
    }

    // MARK: Persistence

    private func load() {
        guard let storeURL, let data = try? Data(contentsOf: storeURL) else { return }
        do {
            let decoded = try ClipboardArchive.decode(data)
            entries = decoded.entries
            if decoded.needsResave { save() }  // migrate the text-only format once
            removeOrphanedFiles()
            if entries.count > limit { apply(ClipboardHistoryLogic.prune(entries, limit: limit)) }
        } catch {
            // Keep an unreadable file aside rather than overwriting it.
            let aside = storeURL.appendingPathExtension("unreadable")
            try? FileManager.default.removeItem(at: aside)
            try? FileManager.default.moveItem(at: storeURL, to: aside)
            NSLog("Lodestar: clipboard history was unreadable; moved it to \(aside.path)")
        }
    }

    private func removeOrphanedFiles() {
        guard let names = try? FileManager.default.contentsOfDirectory(atPath: filesDirectory.path) else { return }
        for name in ClipboardArchive.orphanedFiles(names, entries: entries) {
            try? FileManager.default.removeItem(at: fileURL(name))
        }
    }

    private func save() {
        guard let storeURL else { return }
        do {
            try FileManager.default.createDirectory(at: storeURL.deletingLastPathComponent(), withIntermediateDirectories: true)
            try ClipboardArchive.encode(entries).write(to: storeURL, options: .atomic)
            // Clipboard contents can be sensitive: keep the file owner-only.
            try FileManager.default.setAttributes([.posixPermissions: 0o600], ofItemAtPath: storeURL.path)
        } catch {
            NSLog("Lodestar: failed to save clipboard history: \(error)")
        }
    }

    /// Writes an owner-only file into the (owner-only) clipboard folder.
    private func writeFile(_ name: String, _ data: Data) -> Bool {
        let fm = FileManager.default
        do {
            try fm.createDirectory(at: filesDirectory, withIntermediateDirectories: true, attributes: [.posixPermissions: 0o700])
            try fm.setAttributes([.posixPermissions: 0o700], ofItemAtPath: filesDirectory.path)
        } catch {
            NSLog("Lodestar: can't create \(filesDirectory.path): \(error)")
            return false
        }
        guard fm.createFile(atPath: fileURL(name).path, contents: data, attributes: [.posixPermissions: 0o600]) else {
            NSLog("Lodestar: can't write clipboard file \(name)")
            return false
        }
        return true
    }
}

/// Turns pasteboard image data into a PNG, a small thumbnail, its pixel size
/// and a digest. Runs off the main thread.
enum ClipboardImageProcessor {
    struct Result {
        let png: Data
        let thumbnail: Data?
        let width: Int
        let height: Int
        let digest: String
    }

    static func process(_ data: Data, isPNG: Bool) -> Result? {
        guard data.count <= ClipboardHistory.maxImageBytes * 2,
              let source = CGImageSourceCreateWithData(data as CFData, nil),
              CGImageSourceGetCount(source) > 0,
              let props = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = props[kCGImagePropertyPixelWidth] as? Int,
              let height = props[kCGImagePropertyPixelHeight] as? Int, width > 0, height > 0 else { return nil }
        let png: Data
        if isPNG {
            png = data
        } else {
            guard let image = CGImageSourceCreateImageAtIndex(source, 0, nil), let encoded = encodePNG(image) else { return nil }
            png = encoded
        }
        guard png.count <= ClipboardHistory.maxImageBytes else {
            NSLog("Lodestar: skipped a \(png.count / 1_048_576) MB clipboard image (limit \(ClipboardHistory.maxImageBytes / 1_048_576) MB)")
            return nil
        }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: ClipboardHistory.thumbnailPixels,
        ]
        let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary).flatMap(encodePNG)
        let digest = SHA256.hash(data: png).map { String(format: "%02x", $0) }.joined()
        return Result(png: png, thumbnail: thumbnail, width: width, height: height, digest: digest)
    }

    static func encodePNG(_ image: CGImage) -> Data? {
        let out = NSMutableData()
        guard let dest = CGImageDestinationCreateWithData(out, UTType.png.identifier as CFString, 1, nil) else { return nil }
        CGImageDestinationAddImage(dest, image, nil)
        return CGImageDestinationFinalize(dest) ? out as Data : nil
    }
}

/// `Lodestar --clipboard-selftest`: copies text, RTF text, a link, a color, a
/// PNG, a file URL and a concealed item onto a private pasteboard, captures
/// each into a temporary history, and checks what was recorded.
enum ClipboardSelfTest {
    static func run() -> Bool {
        let dir = FileManager.default.temporaryDirectory.appendingPathComponent("lodestar-selftest-\(UUID().uuidString)")
        defer { try? FileManager.default.removeItem(at: dir) }
        let history = ClipboardHistory(limit: 50, storeURL: nil, filesDirectory: dir)
        let pb = NSPasteboard(name: NSPasteboard.Name("io.github.lodestar.selftest.\(UUID().uuidString)"))
        defer { pb.releaseGlobally() }
        var ok = true
        func check(_ condition: Bool, _ message: String) {
            print((condition ? "PASS " : "FAIL ") + message)
            ok = ok && condition
        }

        pb.clearContents(); pb.setString("hello world", forType: .string)
        history.capture(from: pb)
        check(history.entries.first?.kind == .text && history.entries.first?.text == "hello world", "plain text")

        pb.clearContents()
        pb.setString("bold text", forType: .string)
        let rtf = NSAttributedString(string: "bold text", attributes: [.font: NSFont.boldSystemFont(ofSize: 12)])
        if let data = rtf.rtf(from: NSRange(location: 0, length: rtf.length)) { pb.setData(data, forType: .rtf) }
        history.capture(from: pb)
        let rich = history.entries.first?.richText
        check(rich?.format == .rtf && rich.map { FileManager.default.fileExists(atPath: history.fileURL($0.fileName).path) } == true,
              "rich text kept as an RTF side file")

        pb.clearContents(); pb.setString("https://github.com/leoAnimesh/lodestar", forType: .string)
        history.capture(from: pb)
        check(history.entries.first?.kind == .link, "link")

        pb.clearContents(); pb.setString("#0C0D0E", forType: .string)
        history.capture(from: pb)
        check(history.entries.first?.kind == .color, "color")

        pb.clearContents(); pb.writeObjects([URL(fileURLWithPath: "/etc/hosts") as NSURL])
        history.capture(from: pb)
        check(history.entries.first?.kind == .file && history.entries.first?.filePaths == ["/etc/hosts"], "file URL")

        let before = history.entries.count
        pb.clearContents(); pb.setString("secret", forType: .string)
        pb.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType"))
        history.capture(from: pb)
        check(history.entries.count == before, "concealed item skipped")

        // An image (TIFF only, as many apps provide): converted to PNG off the main thread.
        let image = NSImage(size: NSSize(width: 64, height: 32))
        image.lockFocus(); NSColor.systemOrange.setFill(); NSRect(x: 0, y: 0, width: 64, height: 32).fill(); image.unlockFocus()
        pb.clearContents(); pb.setData(image.tiffRepresentation, forType: .tiff)
        history.capture(from: pb)
        history.workQueue.sync {}
        RunLoop.main.run(until: Date().addingTimeInterval(0.2))
        let entry = history.entries.first
        check(entry?.kind == .image, "image recorded")
        if let info = entry?.image {
            let attrs = try? FileManager.default.attributesOfItem(atPath: history.fileURL(info.fileName).path)
            let mode = (attrs?[.posixPermissions] as? NSNumber)?.intValue ?? 0
            let dirMode = ((try? FileManager.default.attributesOfItem(atPath: dir.path))?[.posixPermissions] as? NSNumber)?.intValue ?? 0
            check(info.width > 0 && info.height > 0 && info.byteSize > 0, "image size \(info.width)×\(info.height), \(info.byteSize) bytes")
            check(info.thumbnailFileName != nil, "thumbnail written")
            check(mode == 0o600 && dirMode == 0o700, String(format: "permissions file %o, folder %o", mode, dirMode))
            // Copying the same image again doesn't add a duplicate.
            let count = history.entries.count
            history.capture(from: pb)
            history.workQueue.sync {}
            RunLoop.main.run(until: Date().addingTimeInterval(0.2))
            check(history.entries.count == count, "same image de-duplicated")
            history.remove(entry!.id)
            check(!FileManager.default.fileExists(atPath: history.fileURL(info.fileName).path), "image file deleted with its entry")
        }
        history.clear()
        let leftovers = (try? FileManager.default.contentsOfDirectory(atPath: dir.path)) ?? []
        check(history.entries.isEmpty && leftovers.isEmpty, "clear removes every entry and side file")
        print(ok ? "clipboard self-test passed" : "clipboard self-test FAILED")
        return ok
    }
}
